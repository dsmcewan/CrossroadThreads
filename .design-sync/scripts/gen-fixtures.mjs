// One-off: build .design-sync/previews/_fixtures.ts with real Design/Wing data
// and compact webp data-URI images (so preview cards render actual artwork
// without depending on site-relative /images/ paths that don't exist in the
// design tool). Run from the repo root: node .ds-sync/gen-fixtures.mjs
import sharp from "../../node_modules/sharp/lib/index.js";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const catalog = JSON.parse(readFileSync("src/data/catalog.generated.json", "utf8"));
const PICKS = ["persephone", "rudis", "boudica", "artemis"];

async function dataUri(sourceFile, width) {
  const buf = await sharp(join("crossroad_imgs", sourceFile))
    .resize({ width, withoutEnlargement: true })
    .webp({ quality: 66 })
    .toBuffer();
  return `data:image/webp;base64,${buf.toString("base64")}`;
}

const designs = {};
for (const slug of PICKS) {
  const d = catalog.designs.find((x) => x.slug === slug);
  const card = await dataUri(d.images.sourceFile, 300);
  const full = await dataUri(d.images.sourceFile, 420);
  const ar = d.images.height / d.images.width;
  designs[slug] = {
    ...d,
    images: {
      sourceFile: d.images.sourceFile,
      width: d.images.width,
      height: d.images.height,
      blurDataURL: d.images.blurDataURL,
      card: [{ src: card, width: 300, height: Math.round(300 * ar), format: "webp" }],
      full: [{ src: full, width: 420, height: Math.round(420 * ar), format: "webp" }],
    },
  };
}

const wings = catalog.wings;

const header = `// GENERATED by .ds-sync/gen-fixtures.mjs — real catalog data + inlined webp
// data-URI artwork, so preview cards render without site-relative image paths.
// Regenerate with: node .ds-sync/gen-fixtures.mjs
import type { Design, Wing } from "@/lib/types";

`;

const body =
  `export const wings: Wing[] = ${JSON.stringify(wings, null, 2)};\n\n` +
  Object.entries(designs)
    .map(([k, v]) => `export const ${k}: Design = ${JSON.stringify(v, null, 2)};`)
    .join("\n\n") +
  `\n\nexport const designs: Design[] = [${PICKS.join(", ")}];\n`;

writeFileSync(".design-sync/previews/_fixtures.ts", header + body);
const bytes = Buffer.byteLength(header + body);
console.log(`wrote .design-sync/previews/_fixtures.ts (${(bytes / 1024).toFixed(0)} KB, ${PICKS.length} designs)`);
